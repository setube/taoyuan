/**
 * Get random flavor text for a furniture/room
 */
export function getRandomFlavor(id: string): string {
  const options = FURNITURE_FLAVOR[id]
  if (!options || options.length === 0) {
    return '你仔细观察着这里。'
  }
  const selected = options[Math.floor(Math.random() * options.length)]
  return selected ?? '你仔细观察着这里。'
}
